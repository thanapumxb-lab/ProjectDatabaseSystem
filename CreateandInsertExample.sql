-- ----------------------------------------------------------------------
-- 3. สร้างโครงสร้างตารางใหม่ (ชนิดข้อมูลเป็น NVARCHAR เพื่อรองรับภาษาไทย)
-- ----------------------------------------------------------------------
CREATE TABLE Customer (
    customer_id VARCHAR(10) PRIMARY KEY,
    name NVARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    driver_license VARCHAR(50) UNIQUE NOT NULL,
    house_no NVARCHAR(100) NOT NULL,     
    sub_district NVARCHAR(50) NOT NULL,  
    district NVARCHAR(50) NOT NULL,      
    province NVARCHAR(50) NOT NULL,      
    zip_code VARCHAR(10) NOT NULL       
);

CREATE TABLE Employee (
    employee_id VARCHAR(10) PRIMARY KEY,
    name NVARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    position NVARCHAR(50) NOT NULL
);

CREATE TABLE CarType (
    type_id VARCHAR(10) PRIMARY KEY,
    type_name NVARCHAR(50) NOT NULL,
    description NVARCHAR(255)
);

CREATE TABLE Car (
    car_id VARCHAR(10) PRIMARY KEY, 
    type_id VARCHAR(10) NOT NULL,
    license_plate NVARCHAR(20) UNIQUE NOT NULL, 
    brand NVARCHAR(20) NOT NULL,
    Models NVARCHAR(50) NOT NULL,
    color NVARCHAR(30),
    rental_rate DECIMAL(10,2) NOT NULL, 
    FOREIGN KEY (type_id) REFERENCES CarType(type_id)
);

CREATE TABLE Rental (
    rental_id VARCHAR(10) PRIMARY KEY,
    customer_id VARCHAR(10) NOT NULL,
    car_id VARCHAR(10) NOT NULL,
    employee_id VARCHAR(10) NOT NULL,
    rental_date DATETIME DEFAULT GETDATE(),
    start_date DATETIME NOT NULL,
    return_date DATETIME NOT NULL,
    actual_return_date DATETIME NULL, 
    status NVARCHAR(20) DEFAULT N'Active', 

    FOREIGN KEY (customer_id) REFERENCES Customer(customer_id),
    FOREIGN KEY (car_id) REFERENCES Car(car_id),
    FOREIGN KEY (employee_id) REFERENCES Employee(employee_id),
    CONSTRAINT CHK_RentalDates CHECK (return_date >= start_date) 
);

CREATE TABLE Receipt (
    receipt_id VARCHAR(10) PRIMARY KEY,
    employee_id VARCHAR(10) NOT NULL,
    rental_id VARCHAR(10) UNIQUE NOT NULL, 
    receipt_date DATETIME DEFAULT GETDATE(),
    daily_rate DECIMAL(10,2) NOT NULL, 
    rent_days INT NOT NULL,            
    late_fee DECIMAL(10,2) DEFAULT 0.00, 
    
    FOREIGN KEY (employee_id) REFERENCES Employee(employee_id),
    FOREIGN KEY (rental_id) REFERENCES Rental(rental_id)
);
GO

